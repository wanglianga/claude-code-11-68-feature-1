package com.example.clinicalrecon.repo;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.stereotype.Repository;

import java.math.BigDecimal;
import java.sql.PreparedStatement;
import java.time.OffsetDateTime;
import java.util.List;
import java.util.Map;
import java.util.Optional;

/** 病灶映射候选、确认边（时间线）与映射运行序号。 */
@Repository
public class LesionLinkRepo {
    private final JdbcTemplate jdbc;

    public LesionLinkRepo(JdbcTemplate jdbc) { this.jdbc = jdbc; }

    public record CandidateRow(long id, long subjectId, Long fromLesionId, long toMeasurementId,
                               String relationType, String confidence, BigDecimal score, String rationale,
                               boolean autoGenerated, String status, String decidedBy, OffsetDateTime decidedAt) {}

    public record LinkRow(long id, long subjectId, long readingSessionId, Long fromLesionId, long toLesionId,
                          long toMeasurementId, String relationType, Long candidateId, String confidence,
                          String rationale, String decidedBy, OffsetDateTime createdAt) {}

    public static final RowMapper<CandidateRow> CAND_MAPPER = (rs, i) -> new CandidateRow(
            rs.getLong("id"), rs.getLong("subject_id"),
            rs.getObject("from_lesion_id") == null ? null : rs.getLong("from_lesion_id"),
            rs.getLong("to_measurement_id"), rs.getString("relation_type"), rs.getString("confidence"),
            rs.getBigDecimal("score"), rs.getString("rationale"), rs.getBoolean("auto_generated"),
            rs.getString("status"), rs.getString("decided_by"),
            rs.getTimestamp("decided_at") == null ? null
                    : rs.getTimestamp("decided_at").toInstant().atOffset(java.time.ZoneOffset.UTC));

    public static final RowMapper<LinkRow> LINK_MAPPER = (rs, i) -> new LinkRow(
            rs.getLong("id"), rs.getLong("subject_id"), rs.getLong("reading_session_id"),
            rs.getObject("from_lesion_id") == null ? null : rs.getLong("from_lesion_id"),
            rs.getLong("to_lesion_id"), rs.getLong("to_measurement_id"), rs.getString("relation_type"),
            rs.getObject("candidate_id") == null ? null : rs.getLong("candidate_id"),
            rs.getString("confidence"), rs.getString("rationale"), rs.getString("decided_by"),
            rs.getTimestamp("created_at").toInstant().atOffset(java.time.ZoneOffset.UTC));

    // ---------- 候选 ----------
    public long insertCandidate(long subjectId, Long fromLesionId, long toMeasurementId, String relationType,
                                String confidence, BigDecimal score, String rationale, boolean auto) {
        var kh = new GeneratedKeyHolder();
        jdbc.update(con -> {
            PreparedStatement ps = con.prepareStatement("""
                    insert into lesion_link_candidate(subject_id, from_lesion_id, to_measurement_id,
                        relation_type, confidence, score, rationale, auto_generated)
                    values(?,?,?,?,?,?,?,?)
                    on conflict (from_lesion_id, to_measurement_id, relation_type) do nothing""",
                    new String[]{"id"});
            ps.setLong(1, subjectId);
            ps.setObject(2, fromLesionId);
            ps.setLong(3, toMeasurementId);
            ps.setString(4, relationType);
            ps.setString(5, confidence);
            ps.setBigDecimal(6, score);
            ps.setString(7, rationale);
            ps.setBoolean(8, auto);
            return ps;
        }, kh);
        return kh.getKey() == null ? -1 : kh.getKey().longValue();
    }

    public List<CandidateRow> candidatesOfSubject(long subjectId, String status) {
        if (status == null) {
            return jdbc.query("select * from lesion_link_candidate where subject_id=? order by id",
                    CAND_MAPPER, subjectId);
        }
        return jdbc.query("select * from lesion_link_candidate where subject_id=? and status=? order by id",
                CAND_MAPPER, subjectId, status);
    }

    public List<CandidateRow> listCandidates(String status) {
        if (status == null) return jdbc.query("select * from lesion_link_candidate order by id", CAND_MAPPER);
        return jdbc.query("select * from lesion_link_candidate where status=? order by id", CAND_MAPPER, status);
    }

    public List<CandidateRow> candidatesOfMeasurement(long measurementId) {
        return jdbc.query("select * from lesion_link_candidate where to_measurement_id=? order by id",
                CAND_MAPPER, measurementId);
    }

    public Optional<CandidateRow> findCandidate(long id) {
        return jdbc.query("select * from lesion_link_candidate where id=?", CAND_MAPPER, id)
                .stream().findFirst();
    }

    public void decideCandidate(long id, String status, String decidedBy) {
        jdbc.update("update lesion_link_candidate set status=?, decided_by=?, decided_at=now() where id=?",
                status, decidedBy, id);
    }

    /** 该测量是否已有任何确认边（避免重复确认） */
    public boolean measurementHasLink(long measurementId) {
        return Boolean.TRUE.equals(jdbc.queryForObject(
                "select exists(select 1 from lesion_link where to_measurement_id=?)",
                Boolean.class, measurementId));
    }

    // ---------- 确认边 ----------
    public long insertLink(long subjectId, long readingSessionId, Long fromLesionId, long toLesionId,
                           long toMeasurementId, String relationType, Long candidateId, String confidence,
                           String rationale, String decidedBy) {
        var kh = new GeneratedKeyHolder();
        jdbc.update(con -> {
            PreparedStatement ps = con.prepareStatement("""
                    insert into lesion_link(subject_id, reading_session_id, from_lesion_id, to_lesion_id,
                        to_measurement_id, relation_type, candidate_id, confidence, rationale, decided_by)
                    values(?,?,?,?,?,?,?,?,?,?)
                    on conflict (to_measurement_id, coalesce(from_lesion_id, -1)) do nothing""",
                    new String[]{"id"});
            ps.setLong(1, subjectId);
            ps.setLong(2, readingSessionId);
            ps.setObject(3, fromLesionId);
            ps.setLong(4, toLesionId);
            ps.setLong(5, toMeasurementId);
            ps.setString(6, relationType);
            ps.setObject(7, candidateId);
            ps.setString(8, confidence);
            ps.setString(9, rationale);
            ps.setString(10, decidedBy);
            return ps;
        }, kh);
        return kh.getKey() == null ? -1 : kh.getKey().longValue();
    }

    public List<LinkRow> linksOfSubject(long subjectId) {
        return jdbc.query("select * from lesion_link where subject_id=? order by id", LINK_MAPPER, subjectId);
    }

    public List<LinkRow> allLinks() {
        return jdbc.query("select * from lesion_link order by id", LINK_MAPPER);
    }

    public List<LinkRow> linksToMeasurements(List<Long> measurementIds) {
        if (measurementIds.isEmpty()) return List.of();
        var placeholders = String.join(",", measurementIds.stream().map(x -> "?").toList());
        return jdbc.query("select * from lesion_link where to_measurement_id in (" + placeholders + ") order by id",
                LINK_MAPPER, measurementIds.toArray());
    }

    public void deleteLinksOfReading(long readingSessionId) {
        jdbc.update("delete from lesion_link where reading_session_id=?", readingSessionId);
    }

    /** 分裂/融合判定后改写既有边关系，保留父子集合与审计字段 */
    public void updateRelation(long linkId, String relationType) {
        jdbc.update("update lesion_link set relation_type=? where id=?", relationType, linkId);
    }

    // ---------- 映射运行 ----------
    public long nextRun(long subjectId, String note) {
        var kh = new GeneratedKeyHolder();
        jdbc.update(con -> {
            PreparedStatement ps = con.prepareStatement(
                    "insert into lesion_mapping_run(subject_id, trigger_note) values(?,?)",
                    new String[]{"seq"});
            ps.setLong(1, subjectId);
            ps.setString(2, note);
            return ps;
        }, kh);
        return kh.getKey().longValue();
    }

    public void finishRun(long seq, int changedLinks) {
        jdbc.update("update lesion_mapping_run set changed_links=? where seq=?", changedLinks, seq);
    }

    public long currentSeq() {
        Long v = jdbc.queryForObject("select coalesce(max(seq), 0) from lesion_mapping_run", Long.class);
        return v == null ? 0 : v;
    }

    public List<Map<String, Object>> listRuns() {
        return jdbc.queryForList("""
                select r.seq, r.subject_id, s.subject_key, r.trigger_note, r.changed_links, r.created_at
                from lesion_mapping_run r join subject s on s.id = r.subject_id
                order by r.seq""");
    }
}
