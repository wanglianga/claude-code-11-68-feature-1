package com.example.clinicalrecon.api;

import com.example.clinicalrecon.domain.LesionDtos;
import com.example.clinicalrecon.repo.ImagingRepo;
import com.example.clinicalrecon.repo.LesionLinkRepo;
import com.example.clinicalrecon.repo.MasterDataRepo;
import com.example.clinicalrecon.repo.ReadingRepo;
import com.example.clinicalrecon.service.LesionLinkingService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.web.bind.annotation.*;

import java.util.List;
import java.util.Map;

/**
 * 病灶映射：自动受约束候选 + 人工复核两条路线，服务同一纵向测量。
 * 未确认候选不得参与正式总和；分裂/融合关系在确认时识别并保留父子关系。
 */
@RestController
@RequestMapping("/api/lesion-links")
@Tag(name = "靶病灶-映射", description = "候选生成、人工确认/驳回与确认边；相似位置不等于身份事实")
public class LesionLinkController {
    private final LesionLinkingService linkingService;
    private final LesionLinkRepo linkRepo;
    private final ImagingRepo imagingRepo;
    private final ReadingRepo readingRepo;
    private final MasterDataRepo masterRepo;

    public LesionLinkController(LesionLinkingService linkingService, LesionLinkRepo linkRepo,
                                ImagingRepo imagingRepo, ReadingRepo readingRepo, MasterDataRepo masterRepo) {
        this.linkingService = linkingService;
        this.linkRepo = linkRepo;
        this.imagingRepo = imagingRepo;
        this.readingRepo = readingRepo;
        this.masterRepo = masterRepo;
    }

    @GetMapping("/candidates")
    @Operation(summary = "映射候选列表", description = "含约束打分与理由；status=CANDIDATE 为待阅片员复核，未确认不入正式总和")
    public List<LesionDtos.CandidateOut> candidates(@RequestParam(required = false) String status,
                                                    @RequestParam(required = false) Long subjectId) {
        var rows = subjectId == null ? linkRepo.listCandidates(status)
                : linkRepo.candidatesOfSubject(subjectId, status);
        return rows.stream().map(this::toCandidateOut).toList();
    }

    @PostMapping("/candidates/{id}/confirm")
    @Operation(summary = "确认候选", description = "人工确认映射；同一测量多父自动识别为融合，同父多测量识别为分裂；随后重算该受试者")
    public LesionDtos.LinkOut confirm(@PathVariable long id) {
        return linkingService.confirmCandidate(id);
    }

    @PostMapping("/candidates/{id}/reject")
    @Operation(summary = "驳回候选", description = "驳回后该测量保持未确认，继续排除在正式总和之外")
    public Map<String, Object> reject(@PathVariable long id) {
        linkingService.rejectCandidate(id);
        return Map.of("candidateId", id, "message", "候选已驳回");
    }

    @PostMapping("/manual")
    @Operation(summary = "人工逐次确认落边", description = "无候选时直接建立确认映射；NEW 关系无父病灶，其余关系须指定父病灶")
    public LesionDtos.LinkOut manual(@Valid @RequestBody LesionDtos.ManualLinkIn in) {
        return linkingService.manualLink(in);
    }

    @GetMapping
    @Operation(summary = "确认边（时间线）列表", description = "已确认的病灶身份映射，分裂保留一个父到多个子、融合保留多个父到一个子")
    public List<LesionDtos.LinkOut> links(@RequestParam(required = false) Long subjectId) {
        var rows = subjectId == null ? linkRepo.allLinks() : linkRepo.linksOfSubject(subjectId);
        return rows.stream().map(linkingService::linkOut).toList();
    }

    private LesionDtos.CandidateOut toCandidateOut(LesionLinkRepo.CandidateRow c) {
        String subjectKey = masterRepo.findSubjectById(c.subjectId())
                .map(MasterDataRepo.SubjectRow::subjectKey).orElse("?");
        String fromKey = c.fromLesionId() == null ? null
                : imagingRepo.findLesionById(c.fromLesionId()).map(ImagingRepo.LesionRow::lesionKey).orElse("?");
        var meas = readingRepo.findMeasurementById(c.toMeasurementId());
        String toLesionKey = meas.flatMap(m -> imagingRepo.findLesionById(m.lesionId()))
                .map(ImagingRepo.LesionRow::lesionKey).orElse("?");
        return new LesionDtos.CandidateOut(c.id(), c.subjectId(), subjectKey, c.fromLesionId(), fromKey,
                c.toMeasurementId(), toLesionKey, c.relationType(), c.confidence(), c.score(), c.rationale(),
                c.autoGenerated(), c.status(), c.decidedBy(),
                c.decidedAt() == null ? null : c.decidedAt().toLocalDate());
    }
}
