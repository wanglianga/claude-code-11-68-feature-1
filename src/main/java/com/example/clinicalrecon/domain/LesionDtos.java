package com.example.clinicalrecon.domain;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;
import java.util.Map;

/** 靶病灶纵向域 API 请求/响应载体。 */
public final class LesionDtos {
    private LesionDtos() {}

    // ---------- 影像检查 / 序列 ----------
    public record SeriesIn(
            @NotBlank String seriesKey,
            String modality,
            @NotBlank String sequenceLabel,
            BigDecimal sliceThickness
    ) {}

    public record ScanIn(
            @NotBlank String subjectKey,
            @NotBlank String centerId,
            @NotBlank String scanKey,
            @NotBlank String visitCode,
            @NotNull LocalDate scanDate,
            String modality,
            String scannerModel,
            BigDecimal sliceThickness,
            String contrastSeries,
            String protocolStatus,
            String protocolReason,
            Boolean comparableToBaseline,
            List<SeriesIn> series
    ) {}

    public record ScanOut(
            long id, long subjectId, String subjectKey, String centerId, String scanKey,
            String visitCode, LocalDate scanDate, String modality, String scannerModel,
            BigDecimal sliceThickness, String protocolStatus, String protocolReason,
            boolean comparableToBaseline, List<Map<String, Object>> series
    ) {}

    // ---------- 基线/新发现病灶登记 ----------
    public record LesionIn(
            @NotBlank String subjectKey,
            @NotBlank String lesionKey,
            @NotBlank String bodySite,
            @NotBlank String measurementAxis,
            @NotBlank String scanKey,                 // 登记所依据的检查
            String seriesKey,
            String origin,                            // 默认 BASELINE；随访新发现用 NEW
            String note
    ) {}

    public record LesionOut(
            long id, long subjectId, String subjectKey, String lesionKey, String bodySite,
            String measurementAxis, long baselineScanId, String baselineScanKey,
            Long baselineSeriesId, String origin, String status, String note,
            String registeredBy, LocalDate registeredAt
    ) {}

    // ---------- 随访阅片 ----------
    public record MeasurementIn(
            @NotBlank String lesionKey,
            Boolean isNew,
            Boolean measurable,                       // 默认 true
            BigDecimal diameter,                      // 不可测必须为空（缺值不记零）
            String axis,
            String seriesKey,
            String nonMeasurableReason,
            String contourRef,
            String evidenceRef
    ) {}

    public record ReadingIn(
            @NotBlank String subjectKey,
            @NotBlank String scanKey,
            @NotBlank String reader,
            @NotNull LocalDate readAt,
            String status,                            // 默认 FINAL
            String triggerNote,
            @NotNull List<MeasurementIn> measurements
    ) {}

    public record ReadingOut(
            long id, long subjectId, String subjectKey, long scanId, String scanKey,
            int readingVersion, String reader, LocalDate readAt, String status,
            String triggerNote, List<Map<String, Object>> measurements
    ) {}

    /** 阅片更正：同扫描新版本，旧版本置 SUPERSEDED，仅重算该受试者指标 */
    public record ReadingCorrectionIn(
            @NotBlank String reader,
            @NotNull LocalDate readAt,
            String triggerNote,
            @NotNull List<MeasurementIn> measurements
    ) {}

    // ---------- 映射候选 / 确认 ----------
    public record CandidateOut(
            long id, long subjectId, String subjectKey,
            Long fromLesionId, String fromLesionKey,
            long toMeasurementId, String toLesionKey, String relationType,
            String confidence, BigDecimal score, String rationale,
            boolean autoGenerated, String status, String decidedBy, LocalDate decidedAt
    ) {}

    /** 直接建立确认映射（阅片员逐次确认，无候选时也可手工落边） */
    public record ManualLinkIn(
            Long fromLesionId,                         // 空=新病灶
            @NotNull Long toMeasurementId,
            @NotBlank String relationType,
            String confidence,
            String rationale
    ) {}

    public record LinkOut(
            long id, long subjectId, String subjectKey, long readingSessionId,
            Long fromLesionId, String fromLesionKey, long toLesionId, String toLesionKey,
            long toMeasurementId, String relationType, Long candidateId,
            String confidence, String rationale, String decidedBy
    ) {}

    public record AutoMapOut(
            long subjectId, int candidatesGenerated, int autoConfirmed,
            int pendingReview, List<String> messages
    ) {}

    // ---------- 指标 / 时间线 ----------
    public record MetricOut(
            long id, long subjectId, String subjectKey, long scanId, String scanKey,
            long readingSessionId, String visitCode, LocalDate scanDate,
            int version, long seq,
            BigDecimal sumDiameters, BigDecimal baselineSum, BigDecimal nadirSum,
            BigDecimal pctChangeBaseline, BigDecimal pctChangeNadir,
            String evaluableStatus, boolean comparable, List<String> flags,
            List<Long> contributingLesionIds, Map<String, Object> basis
    ) {}

    public record TimelineNodeOut(
            long lesionId, String lesionKey, String bodySite, String relationType,
            long scanId, String scanKey, String visitCode, LocalDate scanDate,
            Long measurementId, BigDecimal diameter, boolean measurable,
            String nonMeasurableReason, boolean isNew, Long parentLesionId, String confidence
    ) {}

    public record TimelineOut(String subjectKey, List<TimelineNodeOut> nodes) {}

    // ---------- 疗效数据集 ----------
    public record EndpointDatasetIn(
            @NotBlank String name,
            Boolean includeNotEvaluable,               // 默认 false
            Boolean requireComparable,                 // 默认 true
            List<String> subjectKeys                   // 空=全部受试者
    ) {}

    public record EndpointDatasetOut(
            long id, String name, LocalDate createdAt, String createdBy, long seq,
            String ruleVersion, Map<String, Object> gate, int rowCount, List<String> scopeSubjectKeys
    ) {}

    public record EndpointRowOut(
            long id, long datasetId, long subjectId, String subjectKey, long scanId, String scanKey,
            String visitCode, LocalDate scanDate, long metricId, int metricVersion,
            BigDecimal sumDiameters, BigDecimal baselineSum, BigDecimal nadirSum,
            BigDecimal pctChangeBaseline, BigDecimal pctChangeNadir,
            String evaluableStatus, boolean comparable, List<String> flags, Map<String, Object> evidence
    ) {}

    public record EndpointVerifyOut(
            long datasetId, boolean reproducible,
            List<String> changedSubjects, List<Long> extraInReplay, String message
    ) {}
}
